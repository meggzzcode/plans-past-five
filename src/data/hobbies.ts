import type { ImageKey } from "./images";
import { articlesForHobby } from "@/content";
import { bucketForHigh, costBucketLabels, startupRange } from "./equipment";

export type Cost = "free" | "under25" | "under50" | "flexible";
export type Energy = "low" | "medium" | "high";
export type Setting = "home" | "outdoors" | "out"; // out = somewhere new (studio, café, venue)
export type Company = "solo" | "social";
export type Craving =
  "creativity" | "relaxation" | "adventure" | "friendship" | "movement" | "different";

export type Difficulty = "Easy" | "Gentle learning curve" | "Needs a lesson or two";
export type IndoorOutdoor = "indoor" | "outdoor" | "either";

/** Approximate startup spend. Always show with the assumptions note; never present as a price. */
export type StartupBudget = {
  low: number;
  high: number;
  currency: "USD";
  assumptions: string;
};

/** Optional beginner-guide detail layered on top of the seed data. */
export type Enrichment = {
  difficulty: Difficulty;
  startupBudget: StartupBudget;
  timeCommitment: string;
  indoorOutdoor: IndoorOutdoor;
  startSteps: string[]; // 3 to 5
  firstProject: string;
  relatedHobbies: string[]; // hobby slugs
  learningResources: string[]; // generic descriptions only, no named businesses or URLs
  relatedGuides: string[]; // slugs of PUBLISHED articles only
};

export type Hobby = Partial<Enrichment> & {
  id: string;
  slug: string;
  name: string;
  description: string;
  whyYoullLoveIt: string;
  category: "creative" | "cozy" | "social" | "active" | "outdoors" | "bookish";
  settings: Setting[];
  company: Company[];
  minutes: number; // a realistic first session
  timeLabel: string;
  cost: Cost; // approximate beginner spend
  costLabel: string;
  energy: Energy;
  beginner: 1 | 2 | 3; // 1 = start tonight, 3 = needs a lesson or two
  cravings: Craving[];
  supplies: string[];
  optional: string[];
  firstActivity: string;
  tags: string[]; // at-home, outdoors, after-work, weekend, solo, social, creative, active, low-energy, low-cost
  image?: ImageKey;
  productIds: string[];
};

type Seed = Omit<Hobby, "id" | "slug" | "timeLabel" | "costLabel" | "tags"> & {
  extraTags?: string[];
};

/** Card labels come from src/data/equipment.ts so card, profile and budget tool agree. */
const costLabels: Record<Cost, string> = costBucketLabels;

const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

function make(input: Seed): Hobby {
  const slug = slugify(input.name);
  // One source of truth: the cost bucket is derived from the same equipment numbers that
  // drive the profile range and the budget tool. The seed `cost` is only a fallback.
  const range = startupRange(slug);
  const s: Seed = { ...input, cost: range ? bucketForHigh(range.high) : input.cost };
  const tags = new Set<string>(s.extraTags ?? []);
  if (s.settings.includes("home")) tags.add("at-home");
  if (s.settings.includes("outdoors")) tags.add("outdoors");
  if (s.minutes <= 90) tags.add("after-work");
  if (s.minutes >= 90 || s.settings.includes("outdoors") || s.settings.includes("out"))
    tags.add("weekend");
  s.company.forEach((c) => tags.add(c));
  if (s.category === "creative") tags.add("creative");
  if (s.energy === "high" || s.category === "active") tags.add("active");
  if (s.energy === "low") tags.add("low-energy");
  if (s.cost === "free" || s.cost === "under25") tags.add("low-cost");
  const { extraTags: _e, ...rest } = s;
  return {
    ...rest,
    id: slug,
    slug,
    timeLabel:
      s.minutes < 60
        ? `${s.minutes} minutes`
        : s.minutes === 60
          ? "About an hour"
          : `${Math.round(s.minutes / 30) / 2} hours`,
    costLabel: costLabels[s.cost],
    tags: [...tags],
  };
}

