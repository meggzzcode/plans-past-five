#!/usr/bin/env node
// Lists EVERY Amazon link the built site renders: crawls the sitemap of a running production build and
// reads each page's HTML. Writes docs/commerce/AMAZON-LINKS-INVENTORY.csv (one row per product ASIN) and
// docs/commerce/AMAZON-LINKS-INVENTORY.md (summary, search links, other outbound links).
//   node scripts/serve-built.mjs 5990 &    (after `bun run build`)
//   node scripts/amazon-links-inventory.mjs [http://127.0.0.1:5990]
// Read-only against the site. Never prints or stores a tracking ID: it reports whether a link carries a tag.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const base = (process.argv[2] ?? "http://127.0.0.1:5990").replace(/\/$/, "");
const csvCell = (v) => `"${String(v ?? "").replace(/"/g, '""')}"`;

// Catalog facts straight from the generated module (name, brand, status, hold).
const catText = readFileSync(resolve(root, "src/data/catalog.generated.ts"), "utf8");
const cat = new Map();
for (const m of catText.matchAll(
  /\{\s*id: "([^"]+)",\s*name: "((?:[^"\\]|\\.)*)",\s*brand: "((?:[^"\\]|\\.)*)"[\s\S]*?asin: "([A-Z0-9]{10})"[\s\S]*?status: "(\w+)"/g,
)) {
  cat.set(m[4], {
    id: m[1],
    name: JSON.parse(`"${m[2]}"`),
    brand: JSON.parse(`"${m[3]}"`),
    status: m[5],
  });
}
const held = new Set([...catText.matchAll(/id: "([^"]+)"[\s\S]*?hold: "held"/g)].map((m) => m[1]));

const sitemap = await (await fetch(`${base}/sitemap.xml`)).text();
const pages = [...sitemap.matchAll(/<loc>([^<]+)<\/loc>/g)].map((m) => new URL(m[1]).pathname);
const products = new Map(); // asin -> {pages:Set, hrefs:Set}
const searches = new Map(); // url -> pages
const other = new Map(); // external non-Amazon url -> pages
for (const p of pages) {
  const html = await (await fetch(base + p)).text();
  for (const m of html.matchAll(/href="(https?:\/\/[^"]+)"/g)) {
    const href = m[1].replace(/&amp;/g, "&");
    let u;
    try {
      u = new URL(href);
    } catch {
      continue;
    }
    if (/(^|\.)amazon\.com$/i.test(u.hostname)) {
      const dp = /\/dp\/([A-Z0-9]{10})/.exec(u.pathname);
      if (dp) {
        const e = products.get(dp[1]) ?? { pages: new Set(), hrefs: new Set() };
        e.pages.add(p);
        e.hrefs.add(href);
        products.set(dp[1], e);
      } else if (u.pathname.startsWith("/s")) {
        const e = searches.get(href) ?? new Set();
        e.add(p);
        searches.set(href, e);
      }
    } else if (!/planspastfive\.com$|netlify\.app$/i.test(u.hostname)) {
      const e = other.get(href) ?? new Set();
      e.add(p);
      other.set(href, e);
    }
  }
}

const rows = [...products.entries()]
  .map(([asin, e]) => {
    const c = cat.get(asin);
    const tagged = [...e.hrefs].some((h) => /[?&]tag=/.test(h));
    return {
      asin,
      productId: c?.id ?? "(not in catalog)",
      name: c?.name ?? "",
      brand: c?.brand ?? "",
      status: c?.status ?? "unknown",
      ordinaryUrl: `https://www.amazon.com/dp/${asin}`,
      affiliateReadyUrl: `https://www.amazon.com/dp/${asin}?tag=<TRACKING-ID>`,
      linkCarriesTag: tagged ? "YES (unexpected while tracking is off)" : "no",
      pageCount: e.pages.size,
      pages: [...e.pages].sort().join(" "),
    };
  })
  .sort((a, b) => b.pageCount - a.pageCount || a.name.localeCompare(b.name));

const head = Object.keys(rows[0]);
writeFileSync(
  resolve(root, "docs/commerce/AMAZON-LINKS-INVENTORY.csv"),
  [head.join(","), ...rows.map((r) => head.map((h) => csvCell(r[h])).join(","))].join("\n") + "\n",
);
const today = new Date().toISOString().slice(0, 10);
const md = [
  `# Amazon links on the site (generated ${today})`,
  "",
  `Generated by \`node scripts/amazon-links-inventory.mjs\` from a crawl of ${pages.length} sitemap pages of the production build. Do not edit by hand. Full per-product table: \`docs/commerce/AMAZON-LINKS-INVENTORY.csv\`.`,
  "",
  `- Distinct Amazon product links (\`/dp/ASIN\`): **${rows.length}**`,
  `- Links that currently carry a tracking tag: **${rows.filter((r) => r.linkCarriesTag !== "no").length}** (expected 0: tracking is off)`,
  `- Amazon search links (\`/s?k=...\`, product-type cards): **${searches.size}**`,
  `- Other external links on pages (sources and citations, not products): **${other.size}**`,
  "",
  "## How the affiliate tag gets added",
  "Nothing needs uploading link by link. Every on-site Amazon link is built by one function from the product's ASIN and the single entry in `src/config/affiliate.ts`. When that entry is set to approved and active with a tracking ID, every `/dp/ASIN` link and every search link gets `?tag=<ID>` (or `&tag=`) and the Associates statement appears. Copied, printed and exported lists never carry the tag. See `docs/buyer/AFFILIATE-ACTIVATION.md`.",
  "",
  "## Products (most used first)",
  "| ASIN | Product | Brand | Status | On pages |",
  "|---|---|---|---|---|",
  ...rows.map(
    (r) => `| ${r.asin} | ${r.name || r.productId} | ${r.brand} | ${r.status} | ${r.pageCount} |`,
  ),
  "",
  "## Amazon search links (product-type cards)",
  ...[...searches.keys()].sort().map((u) => `- ${u} (${searches.get(u).size} pages)`),
  "",
  "## Other external links (citations and non-product pages; none are shopping links)",
  ...[...other.keys()].sort().map((u) => `- ${u}`),
  "",
].join("\n");
writeFileSync(resolve(root, "docs/commerce/AMAZON-LINKS-INVENTORY.md"), md);
console.log(
  `products ${rows.length}, search links ${searches.size}, other external ${other.size}, pages ${pages.length}`,
);
